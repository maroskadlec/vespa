// Action codes: I=Inspect, R=Replace, A=Adjust, L=Lubricate, C=Clean
export type ActionCode = 'I' | 'R' | 'A' | 'L' | 'C';

export interface ServiceItem {
  name: string;       // Czech name
  action: ActionCode;
  actionLabel: string; // Czech label
  icon: string;       // Material icon name
}

export interface ServiceMilestone {
  id: string;
  kmThreshold: number;    // km milestone (0 for time-only)
  monthsThreshold: number; // months milestone (0 for km-only)
  label: string;           // Display label e.g. "10 000 km"
  items: ServiceItem[];
}

function item(name: string, action: ActionCode, icon: string): ServiceItem {
  const actionLabels: Record<ActionCode, string> = {
    I: 'Zkontrolovat',
    R: 'Vyměnit',
    A: 'Seřídit',
    L: 'Namazat',
    C: 'Vyčistit',
  };
  return { name, action, actionLabel: actionLabels[action], icon };
}

